import type { Localized } from "@thoadd/db/schema";

export type Lang = "it" | "en";

// Italiano di default; l'inglese ripiega sull'italiano se un testo non è tradotto.
export function tr(value: Localized | null | undefined, lang: Lang): string {
  if (!value) return "";
  return (lang === "en" && value.en) || value.it;
}

export const homePath = (lang: Lang) => (lang === "en" ? "/en" : "/");
// Stesso percorso nell'altra lingua: /progetti/x ↔ /en/progetti/x.
export const localePath = (lang: Lang, path: string) => (lang === "en" ? `/en${path === "/" ? "" : path}` : path);

